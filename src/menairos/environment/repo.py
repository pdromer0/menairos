"""The repo layer of ``menairos entorno`` (hito-0.md 3.4).

It writes the composition of :func:`menairos.stacks.compose` into the project
and never overwrites a file: one that is there and equal is ``ok``, and one
that differs is a conflict, listed and left as it is (mergeable files too). Then
it prepares the language tools (``uv sync`` and ``pre-commit install`` for
python-uv) and makes the first commit of a new repo, on ``main``, without a
push. The layer stops at its first step that is not ``ok`` or ``hecho``.
"""

from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, field
from functools import partial
from importlib.resources.abc import Traversable
from pathlib import Path
from typing import Any

from menairos import stacks
from menairos.environment.core import GREEN, Layer, Result, Step, System, maker
from menairos.schemas import apply_defaults

LAYER = "repo"
RERUN = "menairos entorno repo"
MAIN = "main"
FIRST_COMMIT = "chore: estructura inicial (menairos entorno)"
PRE_COMMIT_MARK = "# File generated by pre-commit: https://pre-commit.com"
PRE_COMMIT_INSTALL = ("uv", "run", "--frozen", "pre-commit", "install")
LOCK = "uv.lock"


@dataclass
class Repo:
    """What the repo layer learns as it goes."""

    root: Path
    system: System
    check_only: bool
    say: Callable[[str], None]
    new: bool = False
    composed: dict[str, stacks.StackFile] = field(
        default_factory=dict[str, stacks.StackFile]
    )
    written: list[str] = field(default_factory=list[str])

    def git(self, *args: str, timeout: float = 60) -> Result:
        return self.system.run(["git", *args], self.root, timeout)

    def has_head(self) -> bool:
        return self.git("rev-parse", "-q", "--verify", "HEAD").code == 0


def repo_layer(
    root: Path,
    config: Mapping[str, Any],
    system: System,
    check_only: bool = False,
    roots: Sequence[Traversable] = (stacks.PACKAGE_ROOT,),
    notify: Callable[[str], None] | None = None,
) -> Layer:
    """The repo layer of the project at ``root``."""
    repo = Repo(system.resolve(root), system, check_only, notify or (lambda _: None))
    steps: list[tuple[str, Callable[[], Step]]] = [
        ("git", partial(git_step, repo)),
        ("plantillas", partial(templates_step, repo, config, roots)),
    ]
    try:
        stack = stacks.resolve(apply_defaults("menairos", config), roots)
    except stacks.StackError:
        stack = ()  # templates_step reports it
    for template in stack:
        steps += [
            (name, partial(make, repo)) for name, make in PREPARE.get(template.name, ())
        ]
    steps.append(("primer commit", partial(first_commit_step, repo)))

    layer = Layer(LAYER)
    for index, (_, run) in enumerate(steps):
        layer.steps.append(run())
        if layer.steps[-1].state not in GREEN:
            layer.not_run = [name for name, _ in steps[index + 1 :]]
            break
    return layer


def git_step(repo: Repo) -> Step:
    """A git repo whose top is the root; a new one is born on ``main``."""
    make = maker(LAYER, "git")
    if repo.system.which("git") is None:
        return make("error", "git no está instalado (lo dice la capa local)")
    top = repo.git("rev-parse", "--show-toplevel")
    state = "ok"
    if top.code != 0 and "not a git repository" not in top.err:
        return make("error", f"git no reconoce la carpeta: {top.tail()}")
    if top.code != 0:
        if repo.check_only:
            return make("manual", "la carpeta no es un repo de git", RERUN)
        made = repo.git("init", "-q", "-b", MAIN)
        top = repo.git("rev-parse", "--show-toplevel")
        if made.code != 0 or top.code != 0:
            return make("error", f"git init falló: {made.tail()}")
        state = "hecho"
    real_top = repo.system.resolve(Path(top.out.strip()))
    if real_top != repo.root:
        return make(
            "error",
            f"«{repo.root}» está dentro del repo «{real_top}»: la raíz del proyecto "
            "tiene que ser la de su repo",
        )
    repo.new = not repo.has_head()
    if not repo.new:
        return make(state, "repo con historia")
    branch = repo.git("symbolic-ref", "--short", "HEAD").out.strip()
    if branch != MAIN:
        detail = f"el repo, sin commits, está en la rama «{branch}» y no en {MAIN}"
        if repo.check_only:
            return make("manual", detail, RERUN)
        repo.git("symbolic-ref", "HEAD", f"refs/heads/{MAIN}")
        if repo.git("symbolic-ref", "--short", "HEAD").out.strip() != MAIN:
            return make("error", f"{detail}, y no se pudo cambiar")
        state = "hecho"
    return make(state, f"repo nuevo, en {MAIN}")


def templates_step(
    repo: Repo,
    config: Mapping[str, Any],
    roots: Sequence[Traversable] = (stacks.PACKAGE_ROOT,),
) -> Step:
    """Write what is missing; a file that is there is ``ok`` or a conflict."""
    make = maker(LAYER, "plantillas")
    try:
        repo.composed = stacks.compose(config, roots)
    except stacks.StackError as error:
        problems = list(error.problems)
        detail = "no se pueden componer: " + "; ".join(problems)
        return make("error", detail, lists={"problemas": problems})
    missing: list[str] = []
    modes: list[str] = []
    conflicts: list[str] = []
    for path, wanted in repo.composed.items():
        try:
            problem = placement_problem(repo.root, path, wanted)
        except OSError as error:
            problem = f"no se puede leer: {error.strerror}"
        if problem == "falta":
            missing.append(path)
        elif problem == "bit":
            modes.append(path)
        elif problem:
            conflicts.append(f"{path}: {problem}")
    written: list[str] = []
    if not repo.check_only:
        for path in missing:
            problem = write_new(repo.root, path, repo.composed[path])
            if problem:
                conflicts.append(f"{path}: {problem}")
            else:
                written.append(path)
        for path in list(modes):
            try:
                add_exec_bit(repo.root / path)
            except OSError as error:
                modes.remove(path)
                conflicts.append(f"{path}: no se puede poner el bit: {error.strerror}")
        repo.written += written + modes
    new_key, new = ("faltan", missing) if repo.check_only else ("escritos", written)
    lists = {
        new_key: new,
        "sin_bit_de_ejecucion": modes,
        "conflictos": conflicts,
    }
    lists = {key: value for key, value in lists.items() if value}
    total = len(repo.composed)
    if conflicts:
        detail = (
            f"{len(conflicts)} de {total} ficheros ya existen distintos y no se tocan: "
            "/preparar-entorno los resuelve contigo, uno a uno"
        )
        return make("manual", detail, lists=lists)
    if missing or modes:
        if repo.check_only:
            detail = (
                f"de {total} ficheros, faltan {len(missing)} y {len(modes)} no tienen "
                "el bit de ejecución"
            )
            return make("manual", detail, RERUN, lists=lists)
        detail = (
            f"de {total} ficheros, {len(written)} escritos y {len(modes)} con el bit "
            "de ejecución puesto"
        )
        return make("hecho", detail, lists=lists)
    return make("ok", f"los {total} ficheros están y son iguales")


def placement_problem(root: Path, path: str, wanted: stacks.StackFile) -> str | None:
    """``None`` if the file is there and equal; ``falta``, ``bit`` or a conflict.

    No link is followed: a link on the way, or something that is not a folder
    where one is needed, is a conflict, so nothing is written out of the root.
    """
    parts = Path(path).parts
    node = root
    for index, part in enumerate(parts):
        node = node / part
        where = node.relative_to(root).as_posix()
        if node.is_symlink():
            return f"«{where}» es un enlace simbólico"
        if not node.exists():
            return "falta"
        if index < len(parts) - 1 and not node.is_dir():
            return f"«{where}» no es una carpeta"
    if not node.is_file():
        return "no es un fichero"
    if node.read_bytes() != wanted.text.encode("utf-8"):
        return "existe con otro contenido"
    if wanted.executable and not node.stat().st_mode & 0o111:
        return "bit"
    return None


def write_new(root: Path, path: str, wanted: stacks.StackFile) -> str | None:
    """Create ``path``, never over a file that appeared meanwhile.

    Returns the problem, or ``None`` if it was written.
    The parent folders are made as needed; :func:`placement_problem` already
    checked that none of them is a link.
    """
    target = root / path
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        with target.open("xb") as handle:
            handle.write(wanted.text.encode("utf-8"))
        if wanted.executable:
            add_exec_bit(target)
    except FileExistsError:
        return "apareció mientras se escribía"
    except OSError as error:
        return f"no se pudo escribir: {error.strerror}"
    return None


def add_exec_bit(path: Path) -> None:
    path.chmod(path.stat().st_mode | 0o111)


def uv_sync_step(repo: Repo) -> Step:
    """The project environment, in sync; an existing ``uv.lock`` is never rewritten."""
    make = maker(LAYER, "uv sync")
    if repo.system.which("uv") is None:
        return make("error", "uv no está instalado (lo dice la capa local)")
    locked = (repo.root / LOCK).is_file()
    flags = ["--locked"] if locked else []
    if locked and repo.system.run(["uv", "lock", "--check"], repo.root).code != 0:
        detail = f"{LOCK} no está al día con pyproject.toml, y menairos no lo reescribe"
        return make("manual", detail, "uv lock")
    check = ["uv", "sync", "--check", *flags]
    if repo.system.run(check, repo.root, 300).code == 0:
        return make("ok", "el entorno está al día")
    if repo.check_only:
        return make("manual", "el entorno no está al día", RERUN)
    repo.say("uv sync: preparando el entorno del proyecto…")
    done = repo.system.run(["uv", "sync", *flags], repo.root, 900)
    if done.code != 0:
        return make("error", f"uv sync falló:\n{done.tail()}")
    if repo.system.run(check, repo.root, 300).code != 0:
        return make("error", "tras uv sync, el entorno sigue sin estar al día")
    if locked:
        return make("hecho", "entorno al día")
    repo.written.append(LOCK)
    return make("hecho", f"entorno creado y {LOCK} escrito")


def pre_commit_step(repo: Repo) -> Step:
    """git's pre-commit hook, installed by pre-commit."""
    make = maker(LAYER, "pre-commit")
    install = " ".join(PRE_COMMIT_INSTALL)
    scope, _, hooks_path = (
        repo.git("config", "--show-scope", "--get", "core.hooksPath")
        .out.strip()
        .partition("\t")
    )
    if hooks_path:
        detail = (
            f"core.hooksPath vale «{hooks_path}» (configuración {scope}), y pre-commit "
            "no instala así"
        )
        return make(
            "manual", detail, f"git config --{scope} --unset-all core.hooksPath"
        )
    where = repo.git("rev-parse", "--git-path", "hooks")
    if where.code != 0:
        return make("error", f"git no da su carpeta de hooks: {where.tail()}")
    hook = repo.root / where.out.strip() / "pre-commit"

    def installed() -> bool | None:
        """``True`` if pre-commit's, ``False`` if someone else's, ``None`` if absent."""
        if not hook.is_file():
            return None
        return PRE_COMMIT_MARK in hook.read_text(encoding="utf-8", errors="replace")

    found = installed()
    if found:
        return make("ok", "el hook está instalado")
    if found is False:
        detail = (
            f"ya hay un hook «{hook}» que no es de pre-commit; pre-commit install lo "
            "movería a pre-commit.legacy"
        )
        return make("manual", detail, install)
    if repo.check_only:
        return make("manual", "el hook no está instalado", RERUN)
    done = repo.system.run(PRE_COMMIT_INSTALL, repo.root, 300)
    if done.code != 0:
        return make("error", f"pre-commit install falló:\n{done.tail()}")
    if not installed():
        return make("error", "tras pre-commit install, el hook no está")
    return make("hecho", "hook instalado")


PREPARE: Mapping[str, Sequence[tuple[str, Callable[[Repo], Step]]]] = {
    "python-uv": (("uv sync", uv_sync_step), ("pre-commit", pre_commit_step)),
}
"""What a language template needs once its files are written, by template.

When a second language template arrives, this becomes an order of the manifest
(decision T-11-D1)."""


def first_commit_step(repo: Repo) -> Step:
    """The first commit of a new repo, on ``main`` and with everything; never a push."""
    make = maker(LAYER, "primer commit")
    if not repo.new:
        step = make("ok", "el repo ya tiene historia: no se hace el primer commit")
        if repo.written:
            step.warnings.append(
                "ficheros nuevos sin commit (los commitea quien trabaje en la rama): "
                + ", ".join(repo.written)
            )
        return step
    if repo.check_only:
        return make("manual", "el repo no tiene ningún commit", RERUN)
    if any(
        repo.git("var", ident).code != 0
        for ident in ("GIT_AUTHOR_IDENT", "GIT_COMMITTER_IDENT")
    ):
        return make(
            "manual",
            "git no sabe quién firma el commit: faltan user.name o user.email",
            'git config --global user.name "Tu nombre" && '
            'git config --global user.email "tu@correo"',
        )
    added = repo.git("add", "-A")
    if added.code != 0:
        return make("error", f"git add falló: {added.tail()}")
    staged = [
        p
        for p in repo.git("diff", "--cached", "--name-only", "-z").out.split("\0")
        if p
    ]
    ours = {*repo.composed, LOCK}
    others = [path for path in staged if path not in ours]
    repo.say(
        "primer commit: pasan los hooks de pre-commit (la primera vez, gitleaks se "
        "compila y tarda unos minutos)…"
    )
    done = repo.git("commit", "-q", "-m", FIRST_COMMIT, timeout=1800)
    if done.code != 0:
        detail = (
            "el commit falló; si un hook cambió ficheros, revísalos con git status "
            f"antes de repetir la orden:\n{done.tail()}"
        )
        return make("error", detail)
    left = repo.git("status", "--porcelain").out.strip()
    if not repo.has_head() or left:
        return make("error", f"tras el commit quedan cambios sin commit:\n{left}")
    repo.new = False
    lists = {"fuera_de_las_plantillas": others} if others else None
    detail = f"«{FIRST_COMMIT}» en {MAIN}, con {len(staged)} ficheros; sin push"
    return make("hecho", detail, lists=lists)
